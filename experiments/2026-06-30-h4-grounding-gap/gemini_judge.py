"""Gemini response-judge for the H4 grounding experiment (cross-family).

Scores a tutor (question, [reference context], response) on the four locked
criteria (RUBRIC.md), 1-5 each, via one schema-constrained Gemini call.

Why Gemini and not Claude: the responses under test are generated by Claude
(frontier) and Mistral (SLM). LLM judges exhibit *self-preference / family bias*
-- a Claude judge inflates other Claude outputs (Llama/Mistral do not show this),
so a Claude judge would bias the frontier side of the H4 comparison. The
documented mitigation is a cross-family judge: Gemini is non-Anthropic AND
non-Mistral, so it is unbiased toward BOTH conditions. We use gemini-2.5-pro
(strong + STABLE, not a -preview id) because the literature shows *weak* judges
are the unreliable ones, especially on factuality/reasoning; a strong judge given
both the rubric AND the reference context is the reliable configuration. Both are
supplied here (rubric via build_system_prompt; retrieved passages via context).

H4 caveat (carried in the writeup): this judge is UNCALIBRATED for the
response-grading task -- teacher response-grades were not collected in time, so
its agreement with humans on THIS task is unverified. H4 is reported as
exploratory. (Reframed-H3 validated the LLM-judge approach on the *relevance*
task, lending indirect plausibility only.)

Reuses the approved rubric, system prompt, criteria and scale from
future_work/response_judge_h3b so the rubric stays single-source. Talks to the
Generative Language REST API directly with urllib (no SDK-version coupling; the
auth-key format goes in the x-goog-api-key header). Temperature 0 for
near-determinism; for the writeup, measure test-retest reliability by running a
subset >=2x rather than assuming bit-determinism.

Run (from repo root):
  GEMINI_API_KEY=$(tr -d '[:space:]' < /c/tmp/gemini_key.txt) \
    uv run python "experiments/2026-06-30-h4-grounding-gap/gemini_judge.py"
  ... --limit 4   # smoke-judge the first 4 responses only
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import time
import urllib.request
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from future_work.response_judge_h3b.judge import CRITERIA, SCALE  # noqa: E402
from future_work.response_judge_h3b.prompts import (  # noqa: E402
    build_system_prompt,
    build_user_message,
    load_rubric,
)
from src.retrieval.corpus_loader import load_chunks  # noqa: E402

SCRIPT_DIR = Path(__file__).resolve().parent
RESPONSES_IN = SCRIPT_DIR / "responses.jsonl"
JUDGED_OUT = SCRIPT_DIR / "judged.jsonl"
JUDGE_LOG = SCRIPT_DIR / "judge.log"
CORPUS = REPO_ROOT / "data" / "corpus" / "chunks.jsonl"

MODEL = "gemini-2.5-pro"
ENDPOINT = (
    f"https://generativelanguage.googleapis.com/v1beta/models/{MODEL}:generateContent"
)

logger = logging.getLogger("h4-judge")


def gemini_schema() -> dict:
    """Schema: one {score, justification} object per criterion.

    Gemini's responseSchema requires enum values to be STRINGS (unlike
    Anthropic, which accepts an integer enum). So score is constrained to the
    string enum "1".."5" here and cast back to int at parse time.
    """
    crit = {
        c: {
            "type": "object",
            "properties": {
                "score": {"type": "string", "enum": [str(s) for s in SCALE]},
                "justification": {"type": "string"},
            },
            "required": ["score", "justification"],
        }
        for c in CRITERIA
    }
    return {"type": "object", "properties": crit, "required": list(CRITERIA)}


@dataclass(frozen=True)
class JudgeResult:
    scores: dict[str, int]
    justifications: dict[str, str]
    input_tokens: int
    output_tokens: int
    model: str

    @property
    def mean(self) -> float:
        return sum(self.scores.values()) / len(self.scores)


class GeminiJudge:
    """Scores a tutor response on the four criteria via one Gemini call."""

    def __init__(self, api_key: str, rubric_md: str | None = None) -> None:
        if not api_key:
            raise ValueError("GEMINI_API_KEY is empty")
        self._key = api_key
        self._system = build_system_prompt(rubric_md or load_rubric())
        self._schema = gemini_schema()

    def _call(self, user: str, attempts: int = 5) -> dict:
        """POST one request, retrying transient errors with backoff."""
        payload = {
            "contents": [{"role": "user", "parts": [{"text": user}]}],
            "systemInstruction": {"parts": [{"text": self._system}]},
            "generationConfig": {
                "temperature": 0,
                "responseMimeType": "application/json",
                "responseSchema": self._schema,
            },
        }
        data = json.dumps(payload).encode("utf-8")
        delay = 5.0
        for attempt in range(1, attempts + 1):
            req = urllib.request.Request(
                ENDPOINT,
                data=data,
                headers={
                    "Content-Type": "application/json",
                    "x-goog-api-key": self._key,
                },
                method="POST",
            )
            try:
                with urllib.request.urlopen(req, timeout=120) as resp:
                    return json.loads(resp.read().decode("utf-8"))
            except urllib.error.HTTPError as exc:
                body = exc.read().decode("utf-8", "replace")
                # 4xx other than 429 are real errors (bad request/auth) -> don't retry.
                if exc.code != 429 and 400 <= exc.code < 500:
                    raise ValueError(f"Gemini {exc.code}: {body}") from exc
                if attempt == attempts:
                    raise ValueError(f"Gemini {exc.code} after {attempts}: {body}") from exc
                logger.warning("HTTP %d, retry %d/%d in %.0fs", exc.code, attempt, attempts, delay)
            except Exception as exc:  # noqa: BLE001 transient net
                if attempt == attempts:
                    raise
                logger.warning("err %s, retry %d/%d in %.0fs", exc, attempt, attempts, delay)
            time.sleep(delay)
            delay = min(delay * 2, 60.0)
        raise RuntimeError("unreachable")

    def judge(self, question: str, response: str, context: str | None = None) -> JudgeResult:
        user = build_user_message(question, response, context)
        body = self._call(user)
        cand = body["candidates"][0]
        text = cand["content"]["parts"][0]["text"]
        data = json.loads(text)
        scores, justifs = {}, {}
        for c in CRITERIA:
            block = data[c]
            s = int(block["score"])
            if s not in SCALE:
                raise ValueError(f"criterion {c} score {s} out of range")
            scores[c] = s
            justifs[c] = str(block.get("justification", ""))
        usage = body.get("usageMetadata", {})
        return JudgeResult(
            scores=scores,
            justifications=justifs,
            input_tokens=int(usage.get("promptTokenCount", 0)),
            output_tokens=int(usage.get("candidatesTokenCount", 0)),
            model=MODEL,
        )


def build_context(chunk_ids: list[str], by_id: dict) -> str:
    """Reconstruct the numbered reference-context block the grounded answer saw.

    Ungrounded responses retrieved the same chunks (the runner stores them) but
    were generated without them; we still give the JUDGE the curriculum context
    so factual_accuracy / curriculum_alignment are assessed against the syllabus,
    not the judge's own priors -- the same context for both conditions keeps the
    grading fair across the grounding ablation.
    """
    blocks = [f"[{i}] {by_id[cid].text}" for i, cid in enumerate(chunk_ids, 1) if cid in by_id]
    return "\n\n".join(blocks)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=0, help="judge only first N (0=all)")
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
        handlers=[logging.FileHandler(JUDGE_LOG, encoding="utf-8"), logging.StreamHandler()],
    )

    api_key = os.environ.get("GEMINI_API_KEY", "")
    judge = GeminiJudge(api_key)

    by_id = {c.metadata.chunk_id: c for c in load_chunks(CORPUS)}

    rows = [json.loads(l) for l in RESPONSES_IN.open(encoding="utf-8") if l.strip()]
    if args.limit:
        rows = rows[: args.limit]

    # Resume: skip (query_id, model_role, grounding) already judged.
    done = set()
    if JUDGED_OUT.exists():
        for l in JUDGED_OUT.open(encoding="utf-8"):
            if l.strip():
                r = json.loads(l)
                done.add((r["query_id"], r["model_role"], r["grounding"]))

    n = 0
    with JUDGED_OUT.open("a", encoding="utf-8") as out:
        for r in rows:
            key = (r["query_id"], r["model_role"], r["grounding"])
            if key in done:
                continue
            context = build_context(r.get("retrieved_chunk_ids", []), by_id)
            res = judge.judge(r["query_text"], r["response"], context)
            rec = {
                **{k: r[k] for k in ("query_id", "model_role", "model", "grounding")},
                "scores": res.scores,
                "justifications": res.justifications,
                "judge_mean": res.mean,
                "judge_model": res.model,
                "judge_input_tokens": res.input_tokens,
                "judge_output_tokens": res.output_tokens,
            }
            out.write(json.dumps(rec, ensure_ascii=False) + "\n")
            out.flush()
            n += 1
            logger.info(
                "%s | %s/%s | mean=%.2f | %s",
                r["query_id"], r["model_role"], r["grounding"], res.mean, res.scores,
            )

    logger.info("done: judged %d responses -> %s", n, JUDGED_OUT)


if __name__ == "__main__":
    main()
